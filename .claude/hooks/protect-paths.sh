#!/usr/bin/env bash
# PreToolUse guard: blocks file-tool edits to installer-managed BMAD files and append-only memlogs.
# Exit 2 blocks the tool call and shows stderr to Claude.
f=$(jq -r '.tool_input.file_path // .tool_input.notebook_path // empty')
[ -z "$f" ] && exit 0
root="${CLAUDE_PROJECT_DIR:-$(pwd)}"
rel="${f#"$root"/}"
case "$rel" in
  _bmad/custom/*) exit 0 ;;
  _bmad/*|.claude/skills/*)
    echo "Blocked: $rel is generated by the BMAD installer. Change behavior through _bmad/custom/ overrides (bmad-customize skill)." >&2
    exit 2 ;;
  .memlog.md|*/.memlog.md)
    echo "Blocked: $rel is an append-only decision log. Append with: uv run _bmad/scripts/memlog.py append --workspace <dir> --type <type> --text \"...\"" >&2
    exit 2 ;;
esac
exit 0
