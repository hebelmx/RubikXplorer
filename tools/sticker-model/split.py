"""Story 10.23 split: whole capture groups go to train, tune or held-out (`holdout.json`), never to two sides.

Usage:
    uv run --project tools/sticker-model python tools/sticker-model/split.py [--manifest artifacts/manifest.json]

Without --manifest, verifies the committed `split.json` (recomputing every listed image's SHA-256). With it, also checks
that the committed file is what the manifest builds. Exit 1 on any failure, naming the group or image hash.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

from sticker_common import HOLDOUT_FILE, REPO_ROOT, SIDES, SPLIT_FILE, dump_json, sha256_file

SYNTHETIC_GROUP = "synthetic/sticker-faces"


def sides_for(holdout: dict, groups: list[str]) -> dict[str, str]:
    """held-out and tune groups from `holdout.json`; every other real group trains."""
    sides = {}
    for group in groups:
        if group in holdout["heldout"]:
            sides[group] = "heldout"
        elif group in holdout["tune"]:
            sides[group] = "tune"
        else:
            sides[group] = "train"
    return sides


def build(manifest: dict, holdout: dict) -> dict:
    groups: dict[str, dict] = {}
    for record in manifest["items"]:
        groups.setdefault(
            record["group"],
            {
                "group": record["group"],
                "side": record["side"],
                "kind": "real",
                "device": record["device"],
                "cube": record["cube"],
                "light": record["light"],
                "stickered": record["stickered"],
            },
        )
    synthetic = manifest["synthetic"]
    groups[synthetic["group"]] = {"group": synthetic["group"], "side": "train", "kind": "synthetic", "generator": synthetic["generator"], "seed": synthetic["seed"]}
    return {
        "schemaVersion": 1,
        "note": "Generated by tools/sticker-model/assemble.py from holdout.json; checked by split.py and StickerModelSplitTest.",
        "groups": sorted(groups.values(), key=lambda g: g["group"]),
        "items": [
            {"item": r["item"], "group": r["group"], "side": r["side"], "sha256": r["sha256"], "source": r["source"]}
            for r in sorted(manifest["items"], key=lambda r: r["item"])
        ],
    }


def verify(split: dict, holdout: dict, root: Path | None = REPO_ROOT) -> list[str]:
    """Every failure as a sentence naming the group or the image hash; empty when the split is sound.

    With [root], each item's image is re-hashed from its committed source and must match the recorded hash.
    """
    failures: list[str] = []
    side_of: dict[str, str] = {}
    for group in split["groups"]:
        name, side = group["group"], group["side"]
        if side not in SIDES:
            failures.append(f"group {name} has unknown side {side}")
        if name in side_of and side_of[name] != side:
            failures.append(f"group {name} is on two sides: {side_of[name]} and {side}")
        side_of.setdefault(name, side)
        if group.get("kind") == "synthetic" and side != "train":
            failures.append(f"synthetic group {name} is on {side}; synthetic faces train only")
    for name in holdout["heldout"]:
        if side_of.get(name) != "heldout":
            failures.append(f"holdout.json names {name} held out, but the split has it on {side_of.get(name, 'no side')}")
    for name in holdout["tune"]:
        if side_of.get(name) != "tune":
            failures.append(f"holdout.json names {name} for tuning, but the split has it on {side_of.get(name, 'no side')}")
    overlap = set(holdout["heldout"]) & set(holdout["tune"])
    for name in sorted(overlap):
        failures.append(f"holdout.json names {name} both held out and tune")
    hash_sides: dict[str, set[str]] = defaultdict(set)
    item_group_sides: dict[str, set[str]] = defaultdict(set)
    for item in split["items"]:
        group_side = side_of.get(item["group"])
        if group_side is None:
            failures.append(f"item {item['item']} belongs to unlisted group {item['group']}")
        elif item["side"] != group_side:
            failures.append(f"group {item['group']} is on two sides: item {item['item']} is on {item['side']}, the group on {group_side}")
        if item["group"].startswith("synthetic/") and item["side"] != "train":
            failures.append(f"synthetic item {item['item']} is on {item['side']}; synthetic faces train only")
        digest = item["sha256"]
        if root is not None:
            path = root / item["source"]
            if not path.is_file():
                failures.append(f"item {item['item']}: source {item['source']} is missing")
            else:
                actual = sha256_file(path)
                if actual != digest:
                    failures.append(f"item {item['item']}: image hash {actual} differs from the recorded {digest}")
                digest = actual
        hash_sides[digest].add(item["side"])
        item_group_sides[item["group"]].add(item["side"])
    for digest, sides in sorted(hash_sides.items()):
        if len(sides) > 1:
            failures.append(f"image hash {digest} is on {len(sides)} sides: {', '.join(sorted(sides))}")
    held = [g for g in split["groups"] if g["side"] == "heldout" and g.get("kind") == "real"]
    if held:
        devices = {g["device"] for g in held}
        if len(devices) < 2:
            failures.append(f"held-out groups cover one device only: {sorted(devices)}")
        if {g["stickered"] for g in held} != {True, False}:
            failures.append("held-out groups do not cover both a stickered and a stickerless cube")
        if sum(1 for g in held if "backlit" in g["light"]) < 2:
            failures.append("fewer than two held-out groups are backlit")
    return failures


def main() -> int:
    parser = argparse.ArgumentParser(description="Verify the committed sticker-model split.")
    parser.add_argument("--manifest", type=Path)
    parser.add_argument("--split", type=Path, default=SPLIT_FILE)
    args = parser.parse_args()
    holdout = json.loads(HOLDOUT_FILE.read_text())
    split = json.loads(args.split.read_text())
    failures = verify(split, holdout)
    if args.manifest:
        expected = dump_json(build(json.loads(args.manifest.read_text()), holdout))
        if expected != args.split.read_text():
            failures.append(f"{args.split} is stale: re-run assemble.py")
    for failure in failures:
        print(failure, file=sys.stderr)
    print("split OK" if not failures else f"{len(failures)} split check(s) failed")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
