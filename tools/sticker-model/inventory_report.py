"""Renders `docs/evidence/10-23/inventory.md` from the assembled manifest and inventory (deterministic)."""

from __future__ import annotations

from collections import defaultdict

THIN_GROUPS = 2
THIN_FACES = 12


def _row(*cells: object) -> str:
    return "| " + " | ".join(str(c) for c in cells) + " |"


def coverage(manifest: dict) -> list[dict]:
    """Image-backed faces per device x cube x light (all sides), with the thin flag (fewer than 2 groups or 12 faces)."""
    cells: dict[tuple, dict] = defaultdict(lambda: {"groups": set(), "faces": 0, "sides": set()})
    for record in manifest["items"]:
        key = (record["device"], record["cube"], record["light"])
        cells[key]["groups"].add(record["group"])
        cells[key]["faces"] += 1
        cells[key]["sides"].add(record["side"])
    rows = []
    for (device, cube, light), cell in sorted(cells.items()):
        thin = len(cell["groups"]) < THIN_GROUPS or cell["faces"] < THIN_FACES
        rows.append(
            {
                "device": device,
                "cube": cube,
                "light": light,
                "groups": len(cell["groups"]),
                "faces": cell["faces"],
                "sides": sorted(cell["sides"]),
                "thin": thin,
            }
        )
    return rows


def render(manifest: dict, inventory: dict) -> str:
    items = manifest["items"]
    lines = [
        "# Story 10.23: sticker-reader data inventory",
        "",
        "Generated by `tools/sticker-model/assemble.py` (do not edit by hand; re-run it). Story 10.23 (*A shadow sticker reader",
        "runs beside the Kotlin reads*), SCP 2026-11-22 quick-scan-sticker-reader. Seed "
        + f"`{manifest['seed']}`; assembly is byte-identical across runs (`test_assemble.py`).",
        "",
        "## Summary",
        "",
        f"- **Image-backed real faces used:** {len(items)} "
        + "("
        + ", ".join(f"{side} {sum(1 for r in items if r['side'] == side)}" for side in ("train", "tune", "heldout"))
        + ").",
        f"- **Excluded image faces:** {len(manifest['excluded'])} (listed below with the reason).",
        "- **Synthetic faces:** generated at training time by `synth_faces.py` (seeded), **training side only**; no synthetic",
        "  item is in tune or held-out (checked by `split.py`, `test_split.py` and `StickerModelSplitTest`).",
        "- **Labels:** every used face carries the nine-sticker `truth` of its record (operator-entered or confirmed), in",
        "  Kotlin cell order (row-major). No label is inferred from folder names or the cube state.",
        "- **Alignment check:** for a live or corner face, the dE76 between each crop cell's mean colour and the JSON's measured",
        f"  sticker is computed; the face is used only when the **median over all 9 cells is <= {manifest['alignment']['medianLimit']}** and the",
        f"  **max over the 8 non-centre cells is <= {manifest['alignment']['maxLimit']}** (the centre is left out of the max because a logo",
        "  centre is measured around the logo). Photos carry no measured stickers, so the check does not apply to them (`alignment: null`).",
        "",
        "## Sources",
        "",
        _row("Group", "Side", "Device", "Cube", "Stickered", "Light", "Holds", "Faces", "Image faces used"),
        _row(*["---"] * 9),
    ]
    used = defaultdict(int)
    for record in items:
        used[record["group"]] += 1
    for source in inventory["sources"]:
        lines.append(
            _row(
                f"`{source['group']}`",
                source["side"] if used.get(source["group"]) else "not used",
                source["device"],
                source["cube"],
                "yes" if source["stickered"] else "no",
                source["light"],
                f"{source['pipeline']} (schema {', '.join(str(s) for s in source['schema'])})",
                source["faces"],
                used.get(source["group"], 0),
            )
        )
    lines += [
        "",
        "Pipelines: `live-a2` = `Fixtures/live/*_studio-a` frames (the recorder grid, the centred 80% square split 3x3);",
        "`corner-pre-10.19` = `Fixtures/corner/*/corner-{1,2}` 200x200 holds, three oblique faces each, quads found by",
        "`corner_keypoints.tflite` and unwarped as `unwarp()` orders corners; `photo-s4` = the S4 photos of",
        "`Fixtures/labeled/photo-evaluation.json`, cropped to their `rect`. `live-a` (schema 1) groups hold Lab only.",
        "",
        "## Sources with labels or measurements but no usable face image",
        "",
        _row("Source", "Holds", "Faces", "Why not used"),
        _row(*["---"] * 4),
    ]
    for row in inventory["labOnly"]:
        lines.append(_row(f"`{row['source']}`", row["holds"], row["faces"], row["why"]))
    lines += [
        "",
        f"## Coverage per device x cube x light (image-backed faces, all sides; thin = fewer than {THIN_GROUPS} groups or {THIN_FACES} faces)",
        "",
        _row("Device", "Cube", "Light", "Groups", "Faces", "Sides", "Thin (H1)"),
        _row(*["---"] * 7),
    ]
    rows = coverage(manifest)
    for row in rows:
        lines.append(
            _row(row["device"], row["cube"], row["light"], row["groups"], row["faces"], ", ".join(row["sides"]), "**thin**" if row["thin"] else "")
        )
    thin = [r for r in rows if r["thin"]]
    lines += [
        "",
        f"**{len(thin)} of {len(rows)} cells are thin** ({sum(1 for r in rows if r['groups'] < THIN_GROUPS)} with fewer than "
        f"{THIN_GROUPS} groups, {sum(1 for r in rows if r['faces'] < THIN_FACES)} with fewer than {THIN_FACES} faces). The",
        "human gate **H1** (`human-gate.md`) asks for extra fixture captures in the thin cells, first where nothing exists at all:",
        "",
        "- no Galaxy S24 FE Quick Scan corner capture, no shaded or backlit S24 FE face and no torch-on capture exist;",
        "- no Lenovo corner capture of the stickerless `stlb` cube or the stickered `stkb` cube in front light;",
        "- the backlit groups (`cool`) are Lenovo-only, and the S24 FE groups are studio front light only;",
        "- no capture group is labelled glossy (no glare or gloss condition was recorded), so nothing here can speak to glossy faces.",
        "",
        "Light notes: `corner/lenovo-tb128xu_stla_warm` hold 1 is side-shaded (docs/evidence/10-19/light-check-and-replay.md,",
        "docs/evidence/10-18/d2-side-face-replay.md); `cool` corner groups are backlit; `photo` light was not metered.",
        "",
        "## Excluded faces",
        "",
        _row("Item", "Source", "Reason"),
        _row(*["---"] * 3),
    ]
    for row in manifest["excluded"]:
        lines.append(_row(f"`{row['item']}`", f"`{row['source']}`", row["reason"]))
    lines += [
        "",
        "## Limits",
        "",
        "- Coverage holds only when the held-out groups are taken together: the backlit held-out groups are Lenovo-only, and",
        "  the S24 FE held-out groups are studio front light only.",
        "- Corner crops are unwarped in Python from the saved 200x200 crop, while the Kotlin Lab values were measured on the",
        "  device's analysis frame: the pixels differ.",
        "- Held-out cells hold about 6 faces (54 stickers) each, so any comparison is indicative.",
        "",
    ]
    return "\n".join(lines)
