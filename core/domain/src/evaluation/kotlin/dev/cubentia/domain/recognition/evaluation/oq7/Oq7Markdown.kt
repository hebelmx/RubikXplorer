package dev.cubentia.domain.recognition.evaluation.oq7

import dev.cubentia.domain.cube.Color
import dev.cubentia.domain.recognition.Lab
import java.util.Locale

object Oq7Markdown {
    const val START = "<!-- oq7-results:start -->"
    const val END = "<!-- oq7-results:end -->"
    private const val MISREAD_LIST_LIMIT = 25

    /** Rewrites only the span between the markers; fails naming [fileName] when a marker is missing or repeated. */
    fun replace(
        document: String,
        section: String,
        fileName: String,
    ): String {
        val start = document.indexOf(START)
        val end = document.indexOf(END)
        require(start >= 0 && end > start && document.lastIndexOf(START) == start && document.lastIndexOf(END) == end) {
            "$fileName: expected ordered unique markers $START and $END"
        }
        return document.substring(0, start + START.length) + "\n" + section.trimEnd() + "\n" + document.substring(end)
    }

    fun render(
        report: Oq7Report,
        crossChecks: List<String> = emptyList(),
    ): String =
        buildString {
            appendLine("_Generated by `./gradlew :core:domain:evaluateRecognitionApproaches`; do not edit by hand._")
            appendLine()
            dataSet(report)
            accuracy(report)
            perGroup(report)
            misreads(report)
            badWhite(report)
            logo(report)
            histogram(report)
            size(report)
            if (crossChecks.isNotEmpty()) {
                appendLine()
                appendLine("### Cross-checks")
                appendLine()
                crossChecks.forEach { appendLine("- $it") }
            }
        }

    private fun StringBuilder.dataSet(report: Oq7Report) {
        appendLine("### Data set")
        appendLine()
        appendLine("| Session | Groups | Faces | Stickers | Faces with a frame |")
        appendLine("|---|---:|---:|---:|---:|")
        Session.entries.forEach { session ->
            val groups = report.groups.filter { it.session == session }
            val faces = groups.flatMap { it.faces }
            row(session.label, groups.size, faces.size, faces.sumOf { it.truth.size }, faces.count { it.cells != null })
        }
        appendLine()
        appendLine(
            "`M-loco` folds (tiny MLP ${TinyMlp.INPUTS}→${TinyMlp.HIDDEN} tanh→${TinyMlp.OUTPUTS} softmax, seed ${TinyMlp.SEED}, " +
                "${TinyMlp.EPOCHS} full-batch epochs at learning rate ${number(TinyMlp.LEARNING_RATE, 2)}, " +
                "${TinyMlp.PARAMETERS} parameters = ${TinyMlp.WEIGHT_BYTES} bytes as float32):",
        )
        appendLine()
        appendLine("| Held-out cube | Training cubes | Training stickers | Held-out stickers |")
        appendLine("|---|---|---:|---:|")
        report.loco.folds.forEach {
            row(
                "`${it.heldOut}`",
                it.trainingCubes.joinToString { cube ->
                    "`$cube`"
                },
                it.trainingSize,
                it.testSize,
            )
        }
        appendLine()
    }

    private fun StringBuilder.accuracy(report: Oq7Report) {
        appendLine("### Accuracy and confidently wrong")
        appendLine()
        appendLine(
            "Confident: nearest-center variants when the second-nearest center is ≥ " +
                "${number(NearestCenter.CLOSE_CALL_DELTA_E, 0)} ΔE farther; " +
                "`M-loco` when its top probability ≥ ${number(TinyMlp.CONFIDENT_PROBABILITY, 2)}. " +
                "Confidently wrong = misread and confident; " +
                "the rate is over classified stickers, against the ≤ 0.1% target.",
        )
        appendLine()
        appendLine(
            "| Variant | Scope | Classified | Correct | Accuracy | Confidently wrong | CW rate | Observed ≤ 0.1% | Uncertain | Not scored |",
        )
        appendLine("|---|---|---:|---:|---:|---:|---:|---|---:|---|")
        Variant.entries.forEach { variant ->
            report.scopes.getValue(variant).forEach { scope ->
                val metrics = scope.metrics
                val unscored = notes(scope.unscored)
                if (metrics.classified == 0) {
                    appendLine("| ${variant.id} | ${scope.scope} | 0 | — | — | — | — | — | — | $unscored |")
                } else {
                    row(
                        variant.id,
                        scope.scope,
                        metrics.classified,
                        metrics.correct,
                        percent(metrics.accuracy),
                        metrics.confidentlyWrong,
                        percent(metrics.confidentlyWrongRate),
                        if (metrics.meetsConfidentlyWrongTarget) "yes" else "no",
                        metrics.uncertain,
                        unscored,
                    )
                }
            }
        }
        appendLine()
        appendLine(
            "Zero confidently wrong observed does not show the ≤ 0.1% target is met: by the rule of three, 0 of N is consistent " +
                "with a true rate up to about 3/N at 95% (0.69% for 432 stickers, 0.46% for 648).",
        )
        appendLine()
    }

    private fun StringBuilder.perGroup(report: Oq7Report) {
        appendLine("### Per group")
        appendLine()
        appendLine("Correct / classified (confidently wrong, uncertain).")
        appendLine()
        appendLine("| Group | Session | ${Variant.entries.joinToString(" | ") { it.id }} |")
        appendLine("|---|---|${Variant.entries.joinToString("") { "---|" }}")
        report.groups.forEach { group ->
            val cells =
                Variant.entries.map { variant ->
                    val run = report.run(variant)
                    val note = run.notes.firstOrNull { it.group == group.name }
                    if (note != null) {
                        note.reason
                    } else {
                        val metrics = Metrics.of(run.stickers.filter { it.group.name == group.name })
                        "${metrics.correct}/${metrics.classified} (${metrics.confidentlyWrong}, ${metrics.uncertain})"
                    }
                }
            appendLine("| ${group.name} | ${group.session.label} | ${cells.joinToString(" | ")} |")
        }
        appendLine()
    }

    private fun StringBuilder.misreads(report: Oq7Report) {
        appendLine("### Misreads")
        appendLine()
        Variant.entries.forEach { variant ->
            val wrong = report.run(variant).stickers.filterNot { it.correct }
            when {
                wrong.isEmpty() -> {
                    appendLine("- **${variant.id}**: none.")
                }

                wrong.size > MISREAD_LIST_LIMIT -> {
                    val summary = "${wrong.size} misreads (list omitted above $MISREAD_LIST_LIMIT); ${misreadPairs(wrong)}"
                    appendLine("- **${variant.id}**: $summary.")
                }

                else -> {
                    appendLine(
                        "- **${variant.id}**: " +
                            wrong.joinToString("; ") {
                                val confidence =
                                    it.prediction.confidence.name
                                        .lowercase(Locale.ROOT)
                                "${it.group.name} ${it.face}[${it.index}] ${it.truth}→${it.prediction.color} ($confidence)"
                            } + ".",
                    )
                }
            }
        }
        appendLine()
    }

    private fun misreadPairs(wrong: List<ScoredSticker>): String =
        "by truth→read: " +
            wrong
                .groupingBy { "${it.truth}→${it.prediction.color}" }
                .eachCount()
                .entries
                .sortedWith(compareByDescending<Map.Entry<String, Int>> { it.value }.thenBy { it.key })
                .joinToString { "${it.key} ${it.value}" }

    private fun StringBuilder.badWhite(report: Oq7Report) {
        appendLine("### Calibration sensitivity (bad white)")
        appendLine()
        appendLine(
            "Every group's WHITE center replaced by ${lab(Calibrations.BAD_WHITE)} (the session A non-white patch); " +
                "the other five centers unchanged. " +
                "`K-self`, `O-self` and `M-loco` have no calibration step, so this case does not apply to them.",
        )
        appendLine()
        appendLine("| Variant | Calibration | Classified | Accuracy | Confidently wrong | CW rate | Uncertain |")
        appendLine("|---|---|---:|---:|---:|---:|---:|")
        report.badWhite.forEach { row ->
            listOf("recorded" to row.recorded, "bad white" to row.badWhite).forEach { (name, metrics) ->
                appendLine(
                    "| ${row.variant.id} | $name | ${metrics.classified} | ${percent(metrics.accuracy)} | ${metrics.confidentlyWrong} | " +
                        "${percent(metrics.confidentlyWrongRate)} | ${metrics.uncertain} |",
                )
            }
        }
        appendLine()
        appendLine("Sweep: WHITE(t) = (1 − t)·recorded + t·bad, per record.")
        appendLine()
        row(
            "t",
            "K-cal accuracy",
            "K-cal confidently wrong",
            "K-cal uncertain",
            "O-cal accuracy",
            "O-cal confidently wrong",
            "O-cal uncertain",
        )
        appendLine("|---:|---:|---:|---:|---:|---:|---:|")
        report.sweep.forEach { row ->
            appendLine(
                "| ${number(row.t, 2)} | ${percent(row.kCal.accuracy)} | ${row.kCal.confidentlyWrong} | ${row.kCal.uncertain} | " +
                    "${percent(row.oCal.accuracy)} | ${row.oCal.confidentlyWrong} | ${row.oCal.uncertain} |",
            )
        }
        appendLine()
    }

    private fun StringBuilder.logo(report: Oq7Report) {
        appendLine("### Logo centers (A2, WHITE-center face)")
        appendLine()
        appendLine(
            "ΔE is to the mean of the same group's non-center WHITE-truth cells measured the same way (JSON samples for the JSON value, " +
                "O cell means for the O cell mean, O histogram modes for the O mode). Readings: ok / misread color, with c = confident, u = uncertain.",
        )
        appendLine()
        appendLine(
            "| Group | Known logo | JSON center | ΔE | O cell mean | ΔE | O mode | ΔE | Mode share | " +
                "${Variant.entries.joinToString(" | ") { it.id }} |",
        )
        appendLine("|---|---|---|---:|---|---:|---|---:|---:|${Variant.entries.joinToString("") { "---|" }}")
        report.logo.forEach { row ->
            val readings =
                row.readings.joinToString(" | ") { (_, sticker) ->
                    when {
                        sticker == null -> "—"
                        else -> "${if (sticker.correct) "ok" else sticker.prediction.color.name} ${confidenceMark(sticker.prediction)}"
                    }
                }
            row(
                row.group,
                if (row.knownLogo) "yes" else "no",
                lab(row.json),
                optional(row.jsonDeltaE),
                row.oMean?.let(::lab) ?: "—",
                optional(row.oMeanDeltaE),
                row.oMode?.let(::lab) ?: "—",
                optional(row.oModeDeltaE),
                row.modeShare?.let(::percentShort) ?: "—",
                readings,
            )
        }
        appendLine()
        appendLine(
            "`K-self` and `O-self` take the WHITE center from this very cell, so their reading of it is correct by construction; " +
                "their cost shows on the other WHITE stickers (see the histogram test below).",
        )
        appendLine()
    }

    private fun StringBuilder.histogram(report: Oq7Report) {
        appendLine("### Center-cell histogram test (issue #153)")
        appendLine()
        val centers = report.centers
        val plain = centers.count { it.plain }
        appendLine(
            "Plain center = histogram mode share ≥ ${percentShort(LabHistogram.PLAIN_SHARE)}. " +
                "$plain of ${centers.size} A2 centers pass (${percent(if (centers.isEmpty()) 0.0 else plain.toDouble() / centers.size)}).",
        )
        appendLine()
        val faces = centers.map { it.face }.distinct().sorted()
        appendLine("| Group | ${faces.joinToString(" | ") { "$it" }} |")
        appendLine("|---|${faces.joinToString("") { "---:|" }}")
        centers.groupBy { it.group }.forEach { (group, shares) ->
            val cells =
                faces.map { face ->
                    shares.firstOrNull { it.face == face }?.let {
                        val text = percentShort(it.share) + if (it.knownLogo) " (logo)" else ""
                        if (it.plain) text else "**$text**"
                    } ?: "—"
                }
            appendLine("| $group | ${cells.joinToString(" | ")} |")
        }
        appendLine()
        val failing = centers.filterNot { it.plain }
        appendLine(
            "Failing centers (bold above): " +
                failing.joinToString("; ") { "${it.group} ${it.face} (${it.color}, ${percentShort(it.share)})" }.ifEmpty { "none" } + ".",
        )
        appendLine()
        val logos = centers.filter { it.knownLogo }
        val logoFails = logos.count { !it.plain }
        val plainFails = centers.count { !it.knownLogo && !it.plain }
        val separates = logos.isNotEmpty() && logoFails == logos.size && plainFails == 0
        appendLine(
            "Fully separates the known logo centers (`stka`, `stla` WHITE): **${if (separates) "yes" else "no"}** — " +
                "$logoFails of ${logos.size} flagged, $plainFails false alarms on ${centers.size - logos.size} other centers.",
        )
        appendLine()
        appendLine(
            "`O-self` calibrates WHITE from the center cell's mode. Known logo centers, against the group's plain WHITE modes " +
                "(within the close-call margin = ΔE < ${number(NearestCenter.CLOSE_CALL_DELTA_E, 0)}):",
        )
        appendLine()
        row(
            "Group",
            "Mode share",
            "ΔE O mode to plain white",
            "Within margin",
            "O-self WHITE stickers correct",
            "Confidently wrong",
            "Uncertain",
        )
        appendLine("|---|---:|---:|---|---:|---:|---:|")
        val oSelf = report.run(Variant.O_SELF)
        report.logo.filter { it.knownLogo }.forEach { row ->
            val whites = oSelf.stickers.filter { it.group.name == row.group && it.truth == Color.WHITE }
            val metrics = Metrics.of(whites)
            val delta = row.oModeDeltaE
            appendLine(
                "| ${row.group} | ${row.modeShare?.let(::percentShort) ?: "—"} | ${optional(delta)} | " +
                    "${if (delta == null) {
                        "—"
                    } else if (delta < NearestCenter.CLOSE_CALL_DELTA_E) {
                        "yes"
                    } else {
                        "no"
                    }} | " +
                    "${metrics.correct}/${metrics.classified} | ${metrics.confidentlyWrong} | ${metrics.uncertain} |",
            )
        }
        appendLine()
    }

    private fun StringBuilder.size(report: Oq7Report) {
        appendLine("### Release size")
        appendLine()
        appendLine(
            "Added runtime bytes per approach. AAR rows: arm64-v8a `.so` uncompressed and compressed " +
                "(as stored in the AAR), classes.jar, " +
                "and the projection used against NFR-11 (arm64 `.so` uncompressed + " +
                "${AarSize.DEX_PROXY_FACTOR} × classes.jar as a dex proxy).",
        )
        appendLine()
        appendLine("| Approach | Runtime | arm64 .so uncompressed | arm64 .so compressed | classes.jar | Projected added |")
        appendLine("|---|---|---:|---:|---:|---:|")
        appendLine("| K (`K-cal`, `K-self`) | Kotlin in `:core:domain` | 0 | 0 | 0 | 0 |")
        val weights = TinyMlp.WEIGHT_BYTES
        row("M (`M-loco`, Kotlin inference)", "Kotlin + $weights weight bytes", 0, 0, 0, bytes(weights.toLong()))
        report.sizes.forEach { aar ->
            val approach =
                when {
                    aar.name.startsWith("opencv") -> "O (`O-cal`, `O-self`)"
                    aar.name.startsWith("litert") -> "M via LiteRT (+ ${TinyMlp.WEIGHT_BYTES} weight bytes)"
                    else -> "—"
                }
            row(
                approach,
                "`${aar.name}`",
                bytes(aar.nativeUncompressed),
                bytes(aar.nativeCompressed),
                bytes(aar.classesJar),
                bytes(aar.projectedAdded),
            )
        }
        appendLine()
        report.sizes.forEach { aar ->
            appendLine("- `${aar.name}` arm64-v8a libraries: ${aar.nativeLibraries.joinToString { "`$it`" }.ifEmpty { "none" }}.")
        }
    }

    private fun notes(notes: List<GroupNote>): String =
        if (notes.isEmpty()) {
            "—"
        } else {
            notes
                .groupBy { it.reason }
                .entries
                .sortedBy { it.key }
                .joinToString("; ") { (reason, groups) -> "${groups.size} group${if (groups.size == 1) "" else "s"}: $reason" }
        }

    private fun confidenceMark(prediction: Prediction) = if (prediction.confidence == Confidence.CONFIDENT) "c" else "u"

    private fun lab(value: Lab) = "L${number(value.l, 1)} a${number(value.a, 1)} b${number(value.b, 1)}"

    private fun optional(value: Double?) = value?.let { number(it, 1) } ?: "—"

    private fun number(
        value: Double,
        decimals: Int,
    ): String {
        val text = String.format(Locale.ROOT, "%.${decimals}f", value)
        return if (text.matches(Regex("-0(\\.0+)?"))) text.removePrefix("-") else text
    }

    private fun StringBuilder.row(vararg cells: Any) {
        appendLine(cells.joinToString(" | ", "| ", " |"))
    }

    private fun percent(value: Double) = String.format(Locale.ROOT, "%.2f%%", value * 100)

    private fun percentShort(value: Double) = String.format(Locale.ROOT, "%.0f%%", value * 100)

    private fun bytes(value: Long) = String.format(Locale.ROOT, "%,d", value)
}
