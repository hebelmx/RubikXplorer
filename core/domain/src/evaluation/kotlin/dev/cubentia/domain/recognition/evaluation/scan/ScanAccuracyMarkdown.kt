package dev.cubentia.domain.recognition.evaluation.scan

import dev.cubentia.domain.recognition.FaceSample
import dev.cubentia.domain.recognition.ScanResult
import dev.cubentia.domain.recognition.SelfCalibration
import dev.cubentia.domain.recognition.StickerClassifier
import dev.cubentia.domain.recognition.StickerConfidence
import java.util.Locale

object ScanAccuracyMarkdown {
    const val START = "<!-- scan-accuracy:start -->"
    const val END = "<!-- scan-accuracy:end -->"

    /** Rewrites only the span between the markers; fails naming [fileName] when a marker is missing or repeated. */
    fun replace(
        document: String,
        section: String,
        fileName: String,
    ): String {
        val start = document.indexOf(START)
        val end = document.indexOf(END)
        require(start >= 0 && end > start && document.lastIndexOf(START) == start && document.lastIndexOf(END) == end) {
            "$fileName: expected ordered unique markers $START and $END"
        }
        return document.substring(0, start + START.length) + "\n" + section.trimEnd() + "\n" + document.substring(end)
    }

    fun render(report: ScanAccuracyReport): String =
        buildString {
            appendLine("_Generated by `./gradlew :core:domain:evaluateScanAccuracy`; do not edit by hand._")
            appendLine()
            dataSet(report)
            perDevice(report)
            perGroup(report)
            misreads(report)
            logoGuard(report)
        }

    private fun StringBuilder.dataSet(report: ScanAccuracyReport) {
        appendLine("### Data set")
        appendLine()
        row("Session", "Groups", "Faces", "Stickers", "Faces with a frame")
        appendLine("|---|---:|---:|---:|---:|")
        Session.entries.forEach { session ->
            val groups = report.groups.filter { it.session == session }
            row(session.label, groups.size, groups.sumOf { it.faces }, groups.sumOf { it.stickers }, groups.sumOf { it.framedFaces })
        }
        appendLine()
        appendLine("Pose recovered from truth (per-face quarter turns that make the six truth faces a valid cube):")
        appendLine()
        Pose.Status.entries.forEach { status ->
            val groups = report.groups.filter { it.pose.status == status }
            if (groups.isNotEmpty()) appendLine("- ${status.label}: ${groups.size} (${groups.joinToString { "`${it.name}`" }})")
        }
        appendLine()
    }

    private fun StringBuilder.perDevice(report: ScanAccuracyReport) {
        appendLine("### Accuracy per device")
        appendLine()
        appendLine(
            "A scan is a group's six faces. Per-scan accuracy = `Full` with all 54 stickers correct; Full and valid = `CubeValidator` " +
                "accepts the read. Confidently wrong = misread and CONFIDENT (second-nearest center ≥ " +
                "${number(StickerClassifier.CLOSE_CALL_DELTA_E, 0)} ΔE farther), against the ≤ 0.1% target.",
        )
        appendLine()
        row(
            "Device",
            "Input",
            "Scans",
            "Full",
            "Per-scan accuracy",
            "Full and valid",
            "Stickers",
            "Correct",
            "Per-sticker accuracy",
            "Confidently wrong",
            "CW rate",
            "Observed ≤ 0.1%",
            "Uncertain",
        )
        appendLine("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---:|")
        val known = ScanAccuracy.DEVICES.map { it.model }.toSet()
        val devices =
            ScanAccuracy.DEVICES +
                report.groups
                    .map { it.model }
                    .distinct()
                    .sorted()
                    .filter { it !in known }
                    .map { Device(it, it) }
        devices.forEach { device ->
            val label = "${device.name} (`${device.model}`)"
            val runs = report.runs.filter { it.model == device.model }
            if (runs.isEmpty()) {
                row(label, "—", "no fixtures", *Array(10) { "—" })
            } else {
                Input.entries.forEach { input -> metricsRow(label, input, runs.filter { it.input == input }) }
            }
        }
        Input.entries.forEach { input -> metricsRow("**Total**", input, report.runs(input)) }
        appendLine()
        appendLine(
            "Zero confidently wrong observed does not show the ≤ 0.1% target is met: by the rule of three, 0 of N is consistent with " +
                "a true rate up to about 3/N at 95% (" +
                Input.entries.joinToString(", ") { input ->
                    val n = report.runs(input).sumOf { it.stickers.size }
                    "${input.label}: ${if (n == 0) "—" else percent(3.0 / n)} for $n stickers"
                } + ").",
        )
        appendLine()
    }

    private fun StringBuilder.metricsRow(
        label: String,
        input: Input,
        runs: List<ScanRun>,
    ) {
        if (runs.isEmpty()) {
            row(label, input.label, 0, *Array(10) { "—" })
            return
        }
        val m = ScanMetrics.of(runs)
        row(
            label,
            input.label,
            m.scans,
            m.full,
            "${m.allCorrect}/${m.scans} (${percent(m.scanAccuracy)})",
            m.fullValid,
            m.stickers,
            m.correct,
            percent(m.stickerAccuracy),
            m.confidentlyWrong,
            percent(m.confidentlyWrongRate),
            if (m.meetsTarget) "yes" else "no",
            m.uncertain,
        )
    }

    private fun StringBuilder.perGroup(report: ScanAccuracyReport) {
        appendLine("### Per group")
        appendLine()
        row("Group", "Session", "Truth", "Input", "Calibration", "Result", "Correct", "Confidently wrong", "Uncertain", "Valid")
        appendLine("|---|---|---|---|---|---|---:|---:|---:|---|")
        report.groups.forEach { group ->
            Input.entries.forEach { input ->
                val run = report.runs.firstOrNull { it.group == group.name && it.input == input }
                if (run == null) {
                    row(group.name, group.session.label, group.pose.status.label, input.label, "—", "no frames", "—", "—", "—", "—")
                } else {
                    val m = ScanMetrics.of(listOf(run))
                    row(
                        group.name,
                        group.session.label,
                        group.pose.status.label,
                        input.label,
                        calibration(run.calibration),
                        result(run),
                        "${m.correct}/${m.stickers}",
                        m.confidentlyWrong,
                        m.uncertain,
                        if (run.valid) "yes" else "no",
                    )
                }
            }
        }
        appendLine()
    }

    private fun calibration(calibration: SelfCalibration): String =
        when (calibration) {
            is SelfCalibration.Calibrated -> {
                if (calibration.guarded.isEmpty()) "self" else "self, ${calibration.guarded.sorted().joinToString("/")} guarded"
            }

            is SelfCalibration.NeedsCalibration -> {
                "needs calibration: ${calibration.colors.sorted().joinToString("/")}"
            }
        }

    private fun result(run: ScanRun): String =
        when (val result = run.result) {
            null -> "not scanned"
            is ScanResult.Full -> "Full"
            is ScanResult.Partial -> "Partial (${result.gaps.entries.joinToString { "${it.key} ${it.value}" }})"
        }

    private fun StringBuilder.misreads(report: ScanAccuracyReport) {
        appendLine("### Misreads")
        appendLine()
        Input.entries.forEach { input ->
            val wrong =
                report.runs(input).flatMap { run -> run.stickers.filterNot { it.correct }.map { run.group to it } }
            if (wrong.isEmpty()) {
                appendLine("- **${input.label}**: none.")
            } else {
                appendLine(
                    "- **${input.label}**: " +
                        wrong.joinToString("; ") { (group, it) ->
                            "$group ${it.face}[${it.index}] ${it.truth}→${it.read} (${it.confidence.name.lowercase(Locale.ROOT)})"
                        } + ".",
                )
            }
        }
        appendLine()
        appendLine("Indices are net positions (row-major per the `Facelets` net), after the pose turned each face.")
        appendLine()
    }

    private fun StringBuilder.logoGuard(report: ScanAccuracyReport) {
        appendLine("### Logo-center guard")
        appendLine()
        appendLine(
            "A center whose histogram mode holds < 60% of its cell is not used as a calibration center. With no saved calibration " +
                "and one guarded color, that color is the mean of the 8 non-center stickers farthest from their nearest trusted " +
                "center. Center-pixel samples carry no mode share, so the guard applies to the Kotlin reader only.",
        )
        appendLine()
        val guarded =
            report.runs.flatMap { run ->
                (run.calibration as? SelfCalibration.Calibrated)
                    ?.guarded
                    .orEmpty()
                    .sorted()
                    .map { run to it }
            }
        val needs = report.runs.filter { it.calibration is SelfCalibration.NeedsCalibration }
        if (guarded.isEmpty() && needs.isEmpty()) {
            appendLine("No center was guarded.")
            appendLine()
            return
        }
        row(
            "Group",
            "Input",
            "Guarded center",
            "Replaced by",
            "Non-center stickers of that color correct",
            "Confidently wrong",
            "Uncertain",
        )
        appendLine("|---|---|---|---|---:|---:|---:|")
        guarded.forEach { (run, color) ->
            // The center's color is fixed by the prompt, so only the eight non-center stickers measure the replacement.
            val stickers = run.stickers.filter { it.truth == color && it.index != FaceSample.CENTER_INDEX }
            row(
                run.group,
                run.input.label,
                color,
                if (run.saved != null) "saved calibration" else "8 farthest stickers",
                "${stickers.count { it.correct }}/${stickers.size}",
                stickers.count { it.confidentlyWrong },
                stickers.count { it.confidence == StickerConfidence.UNCERTAIN },
            )
        }
        needs.forEach { run ->
            val colors = (run.calibration as SelfCalibration.NeedsCalibration).colors.sorted().joinToString("/")
            row(run.group, run.input.label, colors, "not replaced: needs calibration", "—", "—", "—")
        }
        appendLine()
    }

    private fun number(
        value: Double,
        decimals: Int,
    ): String = String.format(Locale.ROOT, "%.${decimals}f", value)

    private fun percent(value: Double) = String.format(Locale.ROOT, "%.2f%%", value * 100)

    private fun StringBuilder.row(vararg cells: Any) {
        appendLine(cells.joinToString(" | ", "| ", " |"))
    }
}
